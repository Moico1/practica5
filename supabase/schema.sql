create extension if not exists vector;

create table if not exists public.normativa_bancaria (
  id bigint generated by default as identity primary key,
  coleccion_id varchar(50) not null,
  contenido text not null,
  fuente_url text not null,
  chunk_index integer not null default 0,
  embedding vector(3072) not null,
  created_at timestamptz not null default now()
);

alter table public.normativa_bancaria enable row level security;

create index if not exists normativa_bancaria_coleccion_idx
  on public.normativa_bancaria using btree (coleccion_id);

create or replace function public.match_normativa_coleccion(
  query_embedding vector(3072),
  match_collection varchar(50),
  match_count integer default 5
)
returns table (
  id bigint,
  contenido text,
  fuente_url text,
  chunk_index integer,
  similarity double precision
)
language sql stable
security invoker
set search_path = public
as $$
  select n.id, n.contenido, n.fuente_url, n.chunk_index,
         1 - (n.embedding <=> query_embedding) as similarity
  from public.normativa_bancaria n
  where n.coleccion_id = match_collection
  order by n.embedding <=> query_embedding
  limit least(greatest(match_count, 1), 100);
$$;
